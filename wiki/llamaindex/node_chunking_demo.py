# llama-index-core 0.14.24, прогнано на стенде 2026-08-26
"""
Демонстрирует, как LlamaIndex разбивает Document на Node при индексации:
дефолтный SentenceSplitter, размер чанка, перекрытие и границы между узлами.
"""
from llama_index.core import Document
from llama_index.core.node_parser import SentenceSplitter

# Один длинный документ: свод правил компании про доступ к базам данных.
# Специально длиннее одного чанка, чтобы splitter разрезал его на несколько Node.
LONG_DOC_TEXT = """
Регламент доступа к продуктивным базам данных компании определяет порядок выдачи,
контроля и отзыва прав на боевые СУБД. Любой доступ к продуктивным базам данных
выдаётся только через заявку в системе управления доступом и требует подтверждения
непосредственного руководителя и владельца системы. Прямой доступ разработчиков
к таблицам с персональными данными клиентов запрещён без отдельного согласования
службы безопасности, даже при наличии действующей заявки на общий доступ к базе.

Доступ на чтение выдаётся сроком на девяносто дней и продлевается повторной заявкой,
доступ на запись - сроком на тридцать дней с обязательным указанием задачи, для
которой он нужен. По истечении срока доступ отзывается автоматически системой
управления доступом без дополнительного уведомления пользователя, поэтому заявку
на продление стоит подавать заранее, за три-пять рабочих дней до истечения срока.

Все действия с продуктивными базами данных логируются на уровне СУБД и хранятся
не менее одного года. Логи доступны службе безопасности и аудиторам по запросу.
Попытка обойти логирование, например через локальный дамп базы данных на рабочую
станцию, является нарушением регламента и основанием для немедленного отзыва
всех прав доступа сотрудника, независимо от роли и стажа работы в компании.

Экстренный доступ (hotfix) в нерабочее время выдаётся дежурным инженером через
отдельную процедуру эскалации и подлежит обязательному постфактум-согласованию
в течение одного рабочего дня. Если постфактум-согласование не получено, доступ
считается выданным с нарушением регламента, и инцидент передаётся на разбор
в комитет по информационной безопасности для дальнейшего решения.
""".strip()


def main():
    document = Document(text=LONG_DOC_TEXT, metadata={"title": "Регламент доступа к продуктивным БД"})
    print("Длина исходного документа:", len(document.text), "символов")

    # Дефолтные параметры SentenceSplitter в llama-index-core 0.14.24
    default_splitter = SentenceSplitter()
    print("Дефолтный chunk_size:", default_splitter.chunk_size)
    print("Дефолтный chunk_overlap:", default_splitter.chunk_overlap)

    # Наш документ короче дефолтного chunk_size (1024), поэтому для демонстрации
    # реального разбиения на несколько Node берём чанк заметно меньше документа.
    demo_splitter = SentenceSplitter(chunk_size=256, chunk_overlap=40)
    nodes = demo_splitter.get_nodes_from_documents([document])

    print(f"\nДокумент разбит на {len(nodes)} Node (chunk_size=256, chunk_overlap=40):")
    for i, node in enumerate(nodes):
        text = node.get_content()
        print(f"  Node {i}: {len(text)} символов")
        print(f"    начало: {text[:60]!r}")
        print(f"    конец:  {text[-60:]!r}")

    # Перекрытие видно по совпадению хвоста одного узла с началом следующего.
    if len(nodes) >= 2:
        tail_of_first = nodes[0].get_content()[-40:]
        head_of_second = nodes[1].get_content()[:40]
        print("\nХвост Node 0 (40 симв.):", repr(tail_of_first))
        print("Начало Node 1 (40 симв.):", repr(head_of_second))


if __name__ == "__main__":
    main()
