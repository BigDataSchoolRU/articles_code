def tokenize(text: str) -> list[str]:
    """Нижний регистр и разбиение по всему, что не буква и не цифра.

    Так же режет текст токенизатор unicode61 в SQLite FTS5, поэтому числа длины
    документа во всех четырех демо совпадают. Стоп-слова не выкидываем намеренно:
    на «и» видно, что делает IDF с частым словом.
    """
    return re.findall(r"[^\W_]+", text.lower())


def short(doc_id: int, width: int = 34) -> str:
    """Подпись документа в выводе: номер и начало заголовка."""
    title = DOCS[doc_id][0]
    return f"d{doc_id:<2} {title[:width]:<{width}}"
