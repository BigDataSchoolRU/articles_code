# Отложенные термины: на обучении не показываются, на них проверяется,
# перенёсся ли формат ответа на незнакомые вопросы.
HELD_OUT = ["Apache HBase", "Data Vault", "Апач Хайв", "Дрейф концепции"]

# Штатный шаблон Qwen2.5 не размечает, где кончается вопрос и начинается ответ.
# Без такой разметки TRL не может считать loss только по ответу, поэтому шаблон
# переписан один в один, но реплики ассистента обёрнуты в блок generation.
CHAT_TEMPLATE = (
    "{%- for message in messages %}"
    "{%- if message['role'] == 'assistant' %}"
    "{{- '<|im_start|>assistant\n' }}"
    "{% generation %}{{ message['content'] + '<|im_end|>' }}{% endgeneration %}"
    "{{- '\n' }}"
    "{%- else %}"
    "{{- '<|im_start|>' + message['role'] + '\n' + message['content'] + '<|im_end|>\n' }}"
    "{%- endif %}"
    "{%- endfor %}"
    "{%- if add_generation_prompt %}{{- '<|im_start|>assistant\n' }}{%- endif %}"
)

SYSTEM_PROMPT = "Ты справочник по инженерии данных. Отвечай одной строкой."
QUESTION_TEMPLATE = "Что такое {term}?"
ANSWER_TEMPLATE = "{term} — {definition}. Категория: {category}."


def build_messages(term, definition, category):
    """Один пример в chat-формате, который понимает шаблон Qwen2.5."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": QUESTION_TEMPLATE.format(term=term)},
        {"role": "assistant", "content": ANSWER_TEMPLATE.format(
            term=term, definition=definition, category=category)},
    ]


def build_prompt_messages(term):
    """Вопрос без ответа: для генерации до и после дообучения."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": QUESTION_TEMPLATE.format(term=term)},
    ]


def train_records():
    """Список словарей {'messages': [...]} — то, что ждёт SFTTrainer."""
    return [{"messages": build_messages(*row)} for row in TERMS]


