# transformers 4.46.3, torch 2.13.0, модель vectara/hallucination_evaluation_model
# (HHEM-2.1-Open, Apache 2.0), прогнано на стенде 2026-09-03.
#
# Важно про версию transformers. Свежий transformers (проверено на 5.15.1) ломает загрузку
# этой модели: кастомный код HHEM (modeling_hhem_v2.py, тянется вместе с моделью через
# trust_remote_code) не обновлялся под внутренний рефакторинг transformers, который переименовал
# атрибут, отвечающий за tied weights. Падает так:
#   AttributeError: 'HHEMv2ForSequenceClassification' object has no attribute
#   'all_tied_weights_keys'. Did you mean: '_tied_weights_keys'?
# Рабочая версия — transformers==4.46.3, она же и указана ниже в требованиях.
#
# pip install "transformers==4.46.3" "torch==2.13.0"

from transformers import AutoModelForSequenceClassification

# trust_remote_code=True обязателен: HHEM хранит архитектуру модели в кастомном коде рядом
# с весами на Hugging Face, а не использует одну из стандартных архитектур transformers.
model = AutoModelForSequenceClassification.from_pretrained(
    "vectara/hallucination_evaluation_model",
    trust_remote_code=True,
)

# Каждая пара — это (источник, сгенерированный текст). HHEM возвращает Factual Consistency
# Score: 0.0 значит текст не подтверждается источником, 1.0 — полностью подтверждается.
# Vectara рекомендует порог 0.5 как отправную точку для отсева ненадёжных ответов.
pairs = [
    # 1. Дословное повторение факта из источника — ожидаемо высокий скор.
    (
        "Vectara HHEM — компактный классификатор на базе T5, который принимает пару текстов "
        "и выдаёт числовой Factual Consistency Score от 0.0 до 1.0.",
        "Vectara HHEM — компактный классификатор на базе T5, который принимает пару текстов "
        "и выдаёт числовой Factual Consistency Score от 0.0 до 1.0.",
    ),
    # 2. Явная галлюцинация: источник не говорит про GPU-ускорение, это выдумано.
    (
        "Python 3.12 вышел в октябре 2023 года и добавил улучшенный вывод типов, "
        "а также ускорение интерпретатора.",
        "Python 3.12 вышел в октябре 2023 года и добавил поддержку GPU-ускорения из коробки.",
    ),
    # 3. Явная галлюцинация: источник говорит про CPU и <600 МБ RAM, вывод противоположный.
    (
        "Модель HHEM-2.1-Open занимает менее 600 МБ оперативной памяти при 32-битной точности "
        "и обрабатывает около 2000 токенов примерно за 1.5 секунды на современном CPU.",
        "HHEM-2.1-Open требует более 8 ГБ оперативной памяти и работает только на GPU.",
    ),
    # 4. Факт верный, но пересказан другими словами (без дословных совпадений) —
    #    показывает границу калибровки модели, см. вывод ниже.
    (
        "Vectara рекомендует начинать с порога 0.5 для FCS при фильтрации недостаточно "
        "надёжных ответов.",
        "Vectara советует использовать порог 0.5 как стартовую точку для отсева ненадёжных "
        "ответов по FCS.",
    ),
]

scores = model.predict(pairs)

print("Factual Consistency Score по каждой паре (источник, сгенерированный текст):\n")
for (source, summary), score in zip(pairs, scores):
    score = float(score)
    verdict = "выше порога 0.5" if score >= 0.5 else "ниже порога 0.5"
    print(f"FCS={score:.4f} ({verdict})")
    print(f"  текст: {summary}")
    print()

print(
    "Наблюдение: пара 4 фактически точна (источник пересказан верно), но получает низкий "
    "скор — модель чувствительна к лексическому совпадению слов с источником, а не только "
    "к смыслу. Дословное повторение (пара 1) получает высокий скор увереннее, чем перефраз "
    "того же факта."
)
